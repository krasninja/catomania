    private void DrawSitting(DrawingContext context, AnimalRenderState state)
    {
        var face = GetFace(state);
        var isDragged = state.State == AnimalAnimationState.Dragged;
        var breathe = isDragged ? 0 : Math.Sin(state.Phase * 0.5) * 4;
        var tail = face == Face.Happy
            ? Math.Sin(state.Phase * 3) * HappyTailWag
            : Math.Sin(state.Phase * 0.7) * TailSway;

        if (!isDragged)
        {
            DrawShadow(context, ShadowBrush, state, DesignSize / 2, 23, 5);
        }

        using (context.PushTransform(SittingToDesign))
        {
            DrawRotated(context, TailBase, tail, () => context.DrawGeometry(_furBrush, TailPen, Tail));

            // The legs dangle and swing when Muchi is picked up.
            var dangle = isDragged
                ? Matrix.CreateTranslation(Math.Sin(state.Phase) * 8, 20)
                : Matrix.Identity;
            using (context.PushTransform(dangle))
            {
                DrawOutlined(context, _furBrush, RightHindLeg);
                DrawOutlined(context, _furBrush, LeftHindLeg);
            }

            DrawOutlined(context, Body, Belly);
            using (context.PushTransform(dangle))
            {
                DrawOutlined(context, _furBrush, LeftForeLeg);
                DrawOutlined(context, _furBrush, RightForeLeg);
            }

            using (context.PushTransform(Matrix.CreateTranslation(0, breathe)))
            {
                DrawOutlined(context, _furBrush, Head);
                DrawFace(context, face, state);
                context.DrawGeometry(Pink, null, InnerEars);
                context.DrawGeometry(Outline, null, EarRims);
            }
        }
    }

    private static void DrawFace(DrawingContext context, Face face, AnimalRenderState state)
    {
        var isRaised = face is Face.Cute or Face.Happy or Face.Meow or Face.Startled;
        var isBlinking = face == Face.Blink || (state.IsBlinking && face is Face.Idle or Face.LookAhead or Face.Cute);
        using (context.PushTransform(Matrix.CreateTranslation(0, isRaised ? -RaisedFaceLift : 0)))
        {
            DrawMuzzle(context, MuzzleCenter, 77, 0, Cheeks);
            switch (face)
            {
                case Face.Meow:
                    DrawOpenMouth(context, new Point(255.5, 244), 15, 15);
                    break;
                case Face.Startled:
                    DrawOpenMouth(context, new Point(255.5, 244), 10, 12);
                    break;
                default:
                    context.DrawGeometry(null, MouthPen, Mouth);
                    break;
            }

            if (isBlinking)
            {
                DrawClosedEyes(context, EyeCenters);
            }
            else if (!isRaised)
            {
                DrawFollowingEyes(context, face, state);
            }

            DrawOutlined(context, Pink, Nose, NosePen);
        }

        // The raised eyes come from the artwork in their place.
        if (!isBlinking)
        {
            switch (face)
            {
                case Face.Cute or Face.Startled:
                    context.DrawGeometry(Outline, null, CutePupils);
                    context.DrawGeometry(White, null, CuteHighlights);
                    break;
                case Face.Happy or Face.Meow:
                    context.DrawGeometry(null, ClosedEyePen, HappyEyes);
                    break;
            }
        }

        using (context.PushTransform(Matrix.CreateTranslation(0, isRaised ? -RaisedWhiskersLift : 0)))
        {
            context.DrawGeometry(null, WhiskerPen, Whiskers);
        }
    }

    // Muchi glances to the left or to the right where the cursor is, only the highlights in the eyes move.
    private static void DrawFollowingEyes(DrawingContext context, Face face, AnimalRenderState state)
    {
        var direction = state.CursorDirection;
        var length = direction.Length;

        // AnimalView mirrors Muchi when it faces left, so compensate to keep the look on the cursor side.
        var side = face == Face.LookAhead || length < double.Epsilon
            ? 0
            : direction.X * (state.FacingRight ? 1 : -1) / length;
        var highlights = side > LookSideThreshold
            ? RightHighlights
            : side < -LookSideThreshold
                ? LeftHighlights
                : Highlights;
        DrawEyes(context, EyeCenters, default, highlights);
    }

    private static void DrawEyes(DrawingContext context, Point[] centers, Vector shift, Vector[] highlights)
    {
        for (var i = 0; i < centers.Length; i++)
        {
            var center = centers[i] + shift;
            context.DrawEllipse(Outline, null, center, EyeRadius, EyeRadius);
            context.DrawEllipse(White, null, center + highlights[i], HighlightRadius, HighlightRadius);
        }
    }

    private static void DrawClosedEyes(DrawingContext context, Point[] centers)
    {
        for (var i = 0; i < centers.Length; i++)
        {
            using (context.PushTransform(Matrix.CreateTranslation(centers[i] - EyeCenters[i])))
            {
                context.DrawGeometry(null, ClosedEyePen, ClosedEyes[i]);
            }
        }
    }

    private static void DrawOpenMouth(DrawingContext context, Point center, double radiusX, double radiusY) =>
        context.DrawEllipse(MouthBrush, MouthPen, center, radiusX, radiusY);

    // The white muzzle and the pink cheeks, the whole face is tilted when Muchi sleeps.
    private static void DrawMuzzle(DrawingContext context, Point center, double radiusY, double angle, Point[] cheeks)
    {
        DrawRotated(context, center, angle, () => context.DrawEllipse(White, null, center, 104.5, radiusY));
        foreach (var cheek in cheeks)
        {
            DrawRotated(context, cheek, angle, () => context.DrawEllipse(Pink, null, cheek, 32, 21));
        }
    }

    // Muchi walks and runs in the same pose, running only takes longer and higher steps.
    private void DrawWalking(DrawingContext context, AnimalRenderState state, Gait gait, double bobHeight)
    {
        var phase = state.Phase;

        // The legs move in diagonal pairs and the body dips as each pair reaches the middle of its stance.
        var midStance = 2 * (phase - (Math.PI * gait.StanceFraction));
        var bob = Math.Cos(midStance) * bobHeight;

        DrawShadow(context, ShadowBrush, state, DesignSize / 2, 27, 5);
        using (context.PushTransform(WalkingToDesign))
        {
            var lift = Matrix.CreateTranslation(0, bob);
            using (context.PushTransform(lift))
            {
                var wag = Math.Sin(phase) * WalkTailWag;
                DrawRotated(context, WalkingTailBase, wag, () => context.DrawGeometry(_furBrush, TailPen, WalkingTail));
            }

            DrawLeg(context, FarForeLeg, FarShoulder, bob, phase, gait);
            DrawLeg(context, FarHindLeg, FarHip, bob, phase + Math.PI, gait);
            using (context.PushTransform(lift))
            {
                DrawOutlined(context, WalkingBody, WalkingBelly);
            }

            DrawLeg(context, NearForeLeg, NearShoulder, bob, phase + Math.PI, gait);
            DrawLeg(context, NearHindLeg, NearHip, bob, phase, gait);
            using (context.PushTransform(lift))
            {
                context.DrawGeometry(null, WhiskerPen, WalkingFarWhiskers);
                DrawOutlined(context, _furBrush, WalkingFarEar);
                DrawOutlined(context, _furBrush, WalkingHead);
                DrawMuzzle(context, WalkingMuzzleCenter, 77, 0, WalkingCheeks);
                context.DrawGeometry(null, MouthPen, WalkingMouth);
                if (state.IsBlinking)
                {
                    DrawClosedEyes(context, WalkingEyeCenters);
                }
                else
                {
                    DrawEyes(context, WalkingEyeCenters, default, Highlights);
                }

                DrawOutlined(context, Pink, WalkingNose, NosePen);
                context.DrawGeometry(Pink, null, WalkingInnerEar);
                context.DrawGeometry(Outline, null, WalkingEarRim);
                context.DrawGeometry(null, WhiskerPen, WalkingNearWhiskers);
            }
        }
    }

    // The hunting trick: Muchi stalks low to the ground with the eyes narrowed, too focused to blink, lashes the tail
    // and wiggles the rear faster and faster, gathers itself even lower and pounces.
    private void DrawHunting(DrawingContext context, AnimalRenderState state)
    {
        var progress = Math.Clamp(state.TrickProgress, 0, 1);
        var stalk = Math.Min(1, progress / HuntGatherStart);
        var wiggle = progress < HuntGatherStart
            ? Math.Sin(stalk * stalk * HuntWiggles * 2 * Math.PI) * HuntWiggleShift * stalk
            : 0;
        var gather = Math.Clamp((progress - HuntGatherStart) / (HuntPounceStart - HuntGatherStart), 0, 1);
        var flight = Math.Clamp((progress - HuntPounceStart) / (1 - HuntPounceStart), 0, 1);
        var arc = Math.Sin(Math.PI * flight);
        var dip = HuntGatherDip * Math.Sin(Math.PI * gather / 2) * (1 - flight);
        var tail = Math.Sin(state.Phase * 3) * HuntTailLash * (1 - arc);

        DrawShadow(context, ShadowBrush, state, DesignSize / 2, 29 * (1 - (0.3 * arc)), 5);
        using (context.PushTransform(HuntingToDesign))
        {
            // The rear wiggles around the front paws, the pounce leans forward in the air.
            var pose = Matrix.CreateRotation(-HuntPounceLean * arc * Math.PI / 180)
                * Matrix.CreateTranslation(0, dip - (HuntPounceHeight * arc));
            using (context.PushTransform(pose))
            {
                using (context.PushTransform(Matrix.CreateTranslation(wiggle, 0)))
                {
                    DrawRotated(context, HuntingTailBase, tail, () => context.DrawGeometry(_furBrush, TailPen, HuntingTail));
                    DrawOutlined(context, _furBrush, HuntingHindLeg);
                }

                DrawOutlined(context, _furBrush, HuntingBody);
                DrawOutlined(context, _furBrush, HuntingForeLeg);
                DrawOutlined(context, _furBrush, HuntingMiddleLeg);
                context.DrawGeometry(null, WhiskerPen, HuntingFarWhiskers);
                DrawOutlined(context, _furBrush, HuntingFarEar);
                DrawOutlined(context, _furBrush, HuntingHead);
                context.DrawGeometry(_furBrush, null, HuntingNearEar);
                context.DrawGeometry(Outline, null, HuntingNearEarRim);
                DrawMuzzle(context, HuntingMuzzleCenter, 55.5, 0, HuntingCheeks);
                context.DrawGeometry(null, MouthPen, HuntingMouth);
                context.DrawGeometry(Outline, null, HuntingPupils);
                context.DrawGeometry(White, null, HuntingHighlights);
                DrawOutlined(context, Pink, HuntingNose, NosePen);
                context.DrawGeometry(null, WhiskerPen, HuntingNearWhiskers);
            }
        }
    }

    // The leg hangs from the hip or the shoulder, which moves with the body, and swings around it to reach the foot
    // position on the ground or in the air. The leg slides along itself into the body or out of it to keep its length,
    // so the planted paw stays on the ground while the leg turns over it.
    private void DrawLeg(DrawingContext context, Geometry leg, Point hip, double bob, double phase, Gait gait)
    {
        var (offsetX, lift) = GetFootOffset(phase, gait);
        var rest = LegReach;
        var reach = new Vector(rest.X + offsetX, rest.Y - lift - bob);
        var angle = Math.Atan2(reach.X, reach.Y) - Math.Atan2(rest.X, rest.Y);
        var slide = rest / rest.Length * (reach.Length - rest.Length);
        var transform = Matrix.CreateTranslation(slide.X, slide.Y)
            * AroundPoint(hip, Matrix.CreateRotation(-angle))
            * Matrix.CreateTranslation(0, bob);
        using (context.PushTransform(transform))
        {
            DrawOutlined(context, _furBrush, leg);
        }
    }

    private void DrawSleepingCurled(DrawingContext context, double phase)
    {
        var breathe = Matrix.CreateTranslation(0, Math.Sin(phase) * 4);

        context.DrawEllipse(ShadowBrush, null, new Point(DesignSize / 2, ShadowY), 34, 5);
        using (context.PushTransform(CurledToDesign))
        {
            context.DrawGeometry(_furBrush, TailPen, CurledTail);
            using (context.PushTransform(breathe))
            {
                DrawOutlined(context, _furBrush, CurledBody);
            }

            foreach (var paw in CurledPaws)
            {
                DrawOutlined(context, _furBrush, paw);
            }

            using (context.PushTransform(breathe))
            {
                DrawOutlined(context, _furBrush, CurledHead);
                context.DrawGeometry(null, ClosedEyePen, CurledEyes);
                DrawMuzzle(context, CurledMuzzleCenter, 77, 15, CurledCheeks);
                context.DrawGeometry(null, MouthPen, CurledMouth);
                DrawOutlined(context, Pink, CurledNose, NosePen);
                context.DrawGeometry(Pink, null, CurledInnerEars);
                context.DrawGeometry(Outline, null, CurledEarRims);
                context.DrawGeometry(null, WhiskerPen, CurledWhiskers);
            }
        }

        DrawZzz(context, ZzzPen, new Point(68, 36), phase);
    }

    // The belly rises with every breath and the paws in the air sway lazily.
    private void DrawSleepingBellyUp(DrawingContext context, double phase)
    {
        var sway = Math.Sin(phase * 0.5) * PawSway;

        context.DrawEllipse(ShadowBrush, null, new Point(DesignSize / 2, ShadowY), 36, 5);
        using (context.PushTransform(BellyUpToDesign))
        {
            context.DrawGeometry(_furBrush, TailPen, BellyUpTail);
            using (context.PushTransform(Matrix.CreateTranslation(0, -(1 + Math.Sin(phase)) * 3)))
            {
                DrawOutlined(context, BellyUpBody, BellyUpBelly);
                DrawRotated(context, ForePawBase, sway, () => DrawOutlined(context, _furBrush, BellyUpForePaw));
                DrawRotated(context, RaisedPawBase, -sway, () => DrawOutlined(context, _furBrush, BellyUpRaisedPaw));
            }

            context.DrawGeometry(null, WhiskerPen, BellyUpFarWhiskers);
            DrawOutlined(context, _furBrush, BellyUpHead);
            context.DrawGeometry(null, ClosedEyePen, BellyUpEyes);
            DrawMuzzle(context, BellyUpMuzzleCenter, 77, 165, BellyUpCheeks);
            context.DrawGeometry(null, MouthPen, BellyUpMouth);
            DrawOutlined(context, Pink, BellyUpNose, NosePen);
            context.DrawGeometry(Pink, null, BellyUpInnerEars);
            context.DrawGeometry(Outline, null, BellyUpEarRims);
            context.DrawGeometry(null, WhiskerPen, BellyUpNearWhiskers);
            DrawRotated(context, HindPawBase, sway, () => DrawOutlined(context, _furBrush, BellyUpHindPaw));
        }

        DrawZzz(context, ZzzPen, new Point(72, 32), phase);
    }

    private static void DrawRotated(DrawingContext context, Point pivot, double angle, Action draw)
    {
        using (context.PushTransform(AroundPoint(pivot, Matrix.CreateRotation(angle * Math.PI / 180))))
        {
            draw();
        }
    }

    private static Matrix AroundPoint(Point point, Matrix transform) => Matrix.CreateTranslation(-point.X, -point.Y)
        * transform
        * Matrix.CreateTranslation(point.X, point.Y);

    private static void DrawOutlined(DrawingContext context, IBrush fill, Geometry geometry) =>
        DrawOutlined(context, fill, geometry, OutlinePen);

    private static void DrawOutlined(DrawingContext context, IBrush fill, Geometry geometry, IPen pen)
    {
        context.DrawGeometry(null, pen, geometry);
        context.DrawGeometry(fill, null, geometry);
    }

    // The fur with a white patch on it, outlined together like a single shape.
    private void DrawOutlined(DrawingContext context, Geometry fur, Geometry patch)
    {
        context.DrawGeometry(null, OutlinePen, fur);
        context.DrawGeometry(null, OutlinePen, patch);
        context.DrawGeometry(_furBrush, null, fur);
        context.DrawGeometry(White, null, patch);
    }

