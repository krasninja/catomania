namespace Catomania.MessageBox;

/// <summary>
/// Icon shown next to the message box text.
/// </summary>
public enum MessageBoxIcon
{
    /// <summary>
    /// Blue circle with an "i", the default icon.
    /// </summary>
    Info,

    /// <summary>
    /// Blue circle with a question mark.
    /// </summary>
    Question,

    /// <summary>
    /// Yellow triangle with an exclamation mark.
    /// </summary>
    Warning,

    /// <summary>
    /// Red circle with a cross.
    /// </summary>
    Error,
}
